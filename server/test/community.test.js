import { test,beforeEach,afterEach } from 'node:test';
import assert from 'node:assert/strict';
import { createTestDb } from '../src/db/connection.js';
import { createRepositories } from '../src/db/repositories.js';
import { makeUser,makeParty,makeSeeker } from './helpers.js';
import { validateAnswers,aggregateAnswers,compareProfiles } from '../src/services/discoveryPreferences.js';
let db,repos;
beforeEach(()=>{
  db=createTestDb();repos=createRepositories(db);
  for(const id of ['h1','h2','friend','seeker','outsider'])repos.users.create(makeUser(id));
  repos.concerts.create({id:'c1',artist:'Act',venue:'Venue',city:'Singapore',event_date:'2020-01-01'});
  repos.parties.create(makeParty('p1',makeUser('h1'),{capacity:2}));
  repos.parties.create(makeParty('p2',makeUser('h2'),{capacity:2}));
  repos.seekers.create(makeSeeker('s1',makeUser('seeker')));
});
afterEach(()=>db.close());
const answers={about:['supper','singalong'],wants:['post concert food'],avoid:[]};
test('one host per concert and one active membership are enforced without removing history',()=>{
  assert.throws(()=>repos.parties.create(makeParty('duplicate',makeUser('h1'))),/already_in_concert_group/);
  repos.membership.configure('h1','p1',{expectedFriends:1});
  const invite=repos.membership.invite('h1','p1');
  repos.membership.acceptInvite('friend',invite.token);
  assert.throws(()=>repos.membership.configure('friend','p2'),/host_required/);
  assert.throws(()=>repos.parties.create(makeParty('friendHosted',makeUser('friend'))),/already_in_concert_group/);
  assert.equal(repos.membership.detail('friend','p1').members.length,2);
  repos.membership.leave('friend','p1');
  assert.equal(db.prepare("SELECT status FROM group_memberships WHERE user_id='friend'").get().status,'left');
});
test('friend links are single use, expiring and hashed; publication waits for all responses',()=>{
  repos.membership.configure('h1','p1',{expectedFriends:1});
  const invite=repos.membership.invite('h1','p1');
  assert.notEqual(db.prepare('SELECT token_hash FROM group_friend_invites').get().token_hash,invite.token);
  assert.throws(()=>repos.membership.publish('h1','p1'),/incomplete/);
  repos.membership.acceptInvite('friend',invite.token);
  assert.throws(()=>repos.membership.acceptInvite('outsider',invite.token),/used/);
  repos.membership.saveAnswers('h1','p1',answers);
  repos.membership.saveAnswers('friend','p1',{about:['quiet'],wants:['supper'],avoid:[]});
  assert.equal(repos.membership.publish('h1','p1',{connectOpen:true}).published,1);
  const profile=repos.membership.profile('p1');
  assert.equal(profile.about.post_supper,0.5);
  assert.equal(profile.wants.post_supper,1);
  assert.throws(()=>repos.membership.saveAnswers('outsider','p1',answers),/member_required/);
});
test('custom terms keep originals, aliases deduplicate and unknown terms never become hard constraints',()=>{
  const parsed=validateAnswers({about:['supper','late-night makan','Rare custom interest'],wants:['supper'],avoid:[]});
  assert.equal(parsed.about.length,2);
  assert.equal(parsed.about[0].key,'post_supper');
  assert.equal(parsed.about[1].recognized,false);
  const result=compareProfiles(aggregateAnswers([parsed]),aggregateAnswers([parsed]));
  assert.equal(result.score,1);
  assert.ok(result.reasons.some(r=>r.concept==='post_supper'));
  assert.throws(()=>validateAnswers({about:[{text:'x',conceptId:'invented'}]}),/unknown_concept/);
});
test('recommendations use member answers, preserve opposite intent, and publish only completed groups',()=>{
 repos.membership.configure('h1','p1',{expectedFriends:0});
 repos.membership.saveAnswers('h1','p1',answers);
 repos.recommendations.savePersonal('seeker','c1',answers);
 assert.ok(!repos.recommendations.individual('seeker','c1').some(g=>g.id==='p1'));
 repos.membership.publish('h1','p1',{connectOpen:true});
 const g=repos.recommendations.individual('seeker','c1').find(g=>g.id==='p1');
 assert.ok(g.reasons.some(r=>r.concept==='post_supper'));
 const negative=compareProfiles(aggregateAnswers([validateAnswers({about:['singalong'],avoid:['supper']})]),repos.membership.profile('p1'));
 assert.ok(negative.score<1);
});
test('seeker chooses once and receiving host approves atomically without a second seeker response',()=>{
 repos.membership.configure('h1','p1',{expectedFriends:0});repos.membership.saveAnswers('h1','p1',answers);repos.membership.publish('h1','p1');
 repos.recommendations.savePersonal('seeker','c1',answers);
 const request=repos.recommendations.requestJoin('seeker','p1');
 assert.equal(repos.parties.findById('p1').remaining_capacity,2);
 assert.throws(()=>repos.recommendations.respond('seeker',request.id,'accept'),/request_not_found/);
 assert.equal(repos.recommendations.respond('h1',request.id,'accept').status,'accepted');
 assert.equal(repos.membership.active('seeker','c1').party_id,'p1');
 assert.equal(repos.parties.findById('p1').remaining_capacity,1);
 assert.throws(()=>repos.recommendations.respond('h1',request.id,'accept'),/not_pending/);
 assert.throws(()=>repos.recommendations.requestJoin('seeker','p2'),/already_in_concert_group/);
 assert.deepEqual(db.pragma('foreign_key_check'),[]);
});
test('notification hooks are persistent, recipient scoped, deduplicated and obey preferences',()=>{
 repos.notifications.chatMessage({messageId:'m1',conversationPath:'/groups/p1/members',senderId:'h1',recipientIds:['h1','friend','friend']});
 repos.notifications.chatMessage({messageId:'m1',conversationPath:'/groups/p1/members',senderId:'h1',recipientIds:['friend']});
 assert.equal(repos.notifications.unread('friend'),1);assert.equal(repos.notifications.unread('h1'),0);
 const n=repos.notifications.list('friend')[0];
 assert.throws(()=>repos.notifications.read('outsider',n.id),/not_found/);
 repos.notifications.read('friend',n.id);assert.equal(repos.notifications.unread('friend'),0);
 repos.notifications.setSettings('friend',{chat:false});
 repos.notifications.chatMessage({messageId:'m2',conversationPath:'/groups/p1/members',senderId:'h1',recipientIds:['friend']});
 assert.equal(repos.notifications.list('friend').length,1);
 assert.throws(()=>repos.notifications.setSettings('friend',{chat:'yes'}),/invalid/);
});
test('join request notifications and business writes share transaction rollback',()=>{
 const operation=db.transaction(()=>{repos.recommendations.requestJoin('seeker','p1');throw new Error('rollback');});
 assert.throws(operation,/rollback/);
 assert.equal(repos.notifications.unread('h1'),0);
 repos.recommendations.requestJoin('seeker','p1');assert.equal(repos.notifications.unread('h1'),1);
});
